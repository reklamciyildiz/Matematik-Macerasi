    fun forGrade(grade: Int): List<Lesson> =
        items.filter { it.grade == grade }.map { it.lesson }

    fun lessonIdsForTopic(grade: Int, topicKey: String): List<String> =
        items.filter { it.grade == grade && it.topicKey == topicKey }.map { it.lesson.id }

    fun forLesson(lesson: Lesson): LessonTeachingScript =
        requireNotNull(items.firstOrNull { it.lesson.id == lesson.id }) {
            "Missing teaching script for " + lesson.id
        }.teachingScript()

    fun all(): List<Entry> = items
}
