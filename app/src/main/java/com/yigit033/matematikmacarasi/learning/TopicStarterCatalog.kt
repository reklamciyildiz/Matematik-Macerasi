package com.yigit033.matematikmacarasi.learning

/**
 * Grade-specific first lessons for the previously empty curriculum headings.
 * Each offers one teachable foundation, NOT the entirety of that heading.
 */
object TopicStarterCatalog {
    data class Entry(
        val grade: Int,
        val topicKey: String,
        val lesson: Lesson,
        val visual: TeachingVisual,
        val model: List<Int>,
        val caption: String,
        val steps: List<String>,
        val misconceptionPrompt: String,
        val correct: String,
        val distractor: String,
        val reasoning: String
    ) {
        fun teachingScript(): LessonTeachingScript = LessonTeachingScript(
            visual = visual,
            headline = lesson.title,
            earlyExplanation = lesson.teaching,
            laterExplanation = lesson.teaching,
            groups = model,
            diagramCaption = caption,
            steps = steps,
            check = LessonConceptCheck(
                misconceptionPrompt, listOf(correct, distractor), 0,
                reasoning, lesson.hint
            )
        )
    }

